-- 1. Tabela de Dispositivos IoT (ESP32 / FIWARE IoT Agent)
CREATE TABLE IF NOT EXISTS public.vine_devices (
    device_id text PRIMARY KEY,
    entity_name text NOT NULL,
    entity_type text NOT NULL DEFAULT 'Vine',
    api_key text NOT NULL DEFAULT 'TEF',
    transport text NOT NULL DEFAULT 'MQTT_REST',
    wokwi_project_url text DEFAULT 'https://wokwi.com/projects/478106752109243393',
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

-- 2. Tabela de Presets de Conservação Enológica (8 Estilos de Vinho)
CREATE TABLE IF NOT EXISTS public.vine_trigger_configs (
    preset_key text PRIMARY KEY,
    name text NOT NULL,
    description text NOT NULL,
    temp_min numeric(5,2) NOT NULL,
    temp_max numeric(5,2) NOT NULL,
    hum_min numeric(5,2) NOT NULL,
    hum_max numeric(5,2) NOT NULL,
    lum_min numeric(5,2) NOT NULL,
    lum_max numeric(5,2) NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

-- 3. Tabela de Séries Históricas de Telemetria e Alertas (ESP32 Físico & Wokwi)
CREATE TABLE IF NOT EXISTS public.vine_telemetry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id text NOT NULL REFERENCES public.vine_devices(device_id) ON DELETE CASCADE,
    temperature numeric(5,2) NOT NULL,
    humidity numeric(5,2) NOT NULL,
    luminosity numeric(5,2) NOT NULL,
    alert_mode text NOT NULL DEFAULT 'normal',
    cellar_health_score integer NOT NULL DEFAULT 100,
    source text NOT NULL DEFAULT 'ESP32 Barril',
    recorded_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_vine_telemetry_device_recorded
    ON public.vine_telemetry USING btree (device_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_vine_telemetry_recorded_desc
    ON public.vine_telemetry USING btree (recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_vine_telemetry_anomalies
    ON public.vine_telemetry USING btree (recorded_at DESC) WHERE alert_mode <> 'normal';

CREATE OR REPLACE FUNCTION public.auto_provision_device()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.vine_devices (device_id, entity_name, entity_type, api_key, transport)
    VALUES (NEW.device_id, 'urn:ngsi-ld:Vine:' || NEW.device_id, 'Vine', 'TEF', 'MQTT_REST')
    ON CONFLICT (device_id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_auto_provision_device ON public.vine_telemetry;
CREATE TRIGGER trg_auto_provision_device
BEFORE INSERT ON public.vine_telemetry
FOR EACH ROW
EXECUTE FUNCTION public.auto_provision_device();

-- 4. Tabela de Status em Tempo Real das 12 Áreas e Terroirs do Mundo
CREATE TABLE IF NOT EXISTS public.real_vineyards_status (
    vineyard_id text PRIMARY KEY,
    name text NOT NULL,
    region text NOT NULL,
