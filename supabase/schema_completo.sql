    humidity_pct numeric(5,2) NOT NULL,
    luminosity_pct numeric(5,2) NOT NULL,
    solar_wm2 numeric(7,2) NOT NULL DEFAULT 0,
    dew_point_c numeric(5,2) NOT NULL DEFAULT 0,
    is_day boolean NOT NULL DEFAULT true,
    local_time text NOT NULL DEFAULT '00:00',
    updated_at timestamp with time zone NOT NULL DEFAULT now()
