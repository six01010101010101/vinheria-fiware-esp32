-- 6. Políticas RLS (Row Level Security) - Leitura e Escrita Públicas para Anon e Authenticated
ALTER TABLE public.vine_devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vine_telemetry ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.real_vineyards_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cellar_lots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vine_trigger_configs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anon all vine_devices" ON public.vine_devices;
CREATE POLICY "Allow anon all vine_devices" ON public.vine_devices FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all vine_telemetry" ON public.vine_telemetry;
CREATE POLICY "Allow anon all vine_telemetry" ON public.vine_telemetry FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all real_vineyards" ON public.real_vineyards_status;
CREATE POLICY "Allow anon all real_vineyards" ON public.real_vineyards_status FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all cellar_lots" ON public.cellar_lots;
CREATE POLICY "Allow anon all cellar_lots" ON public.cellar_lots FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all triggers" ON public.vine_trigger_configs;
CREATE POLICY "Allow anon all triggers" ON public.vine_trigger_configs FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- 7. View Analítica Otimizada para Resumo do Painel
CREATE OR REPLACE VIEW public.v_vine_telemetry_summary
WITH (security_invoker = true) AS
SELECT
    device_id, source, COUNT(*) AS total_readings,
    ROUND(AVG(temperature), 2) AS avg_temp_c, ROUND(MIN(temperature), 2) AS min_temp_c,
    ROUND(MAX(temperature), 2) AS max_temp_c, ROUND(AVG(humidity), 2) AS avg_humidity_pct,
    ROUND(AVG(luminosity), 2) AS avg_luminosity_pct, ROUND(AVG(cellar_health_score), 1) AS avg_health_score,
    COUNT(*) FILTER (WHERE alert_mode <> 'normal') AS anomaly_count, MAX(recorded_at) AS last_recorded_at
FROM public.vine_telemetry GROUP BY device_id, source;

